"""Migration 0001 : aller-retour complet, sans dérive.

Tourne sur une base de migrations dédiée (nom dérivé de `TEST_DATABASE_URL`
en lui ajoutant le suffixe `_migrations`, `url_base_migrations`, L3-D22) pour
ne jamais perturber `bl_test`, que les autres tests supposent toujours
migrée à `head`.
"""

from __future__ import annotations

import asyncio
from typing import Any

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine

from tests.conftest import ALEMBIC_INI, preparer_base, url_base_migrations

pytestmark = pytest.mark.db


def _config(url: str) -> Config:
    config = Config(str(ALEMBIC_INI))
    config.attributes["sqlalchemy_url"] = url
    return config


def _lister_tables(url: str) -> list[str]:
    async def _lister() -> list[str]:
        engine = create_async_engine(url)
        try:
            async with engine.connect() as connexion:
                resultat = await connexion.execute(
                    text(
                        "SELECT tablename FROM pg_tables "
                        "WHERE schemaname = 'public' AND tablename != 'alembic_version'"
                    )
                )
                return sorted(row[0] for row in resultat)
        finally:
            await engine.dispose()

    return asyncio.run(_lister())


def test_upgrade_head_cree_les_23_tables_puis_aller_retour(
    test_database_url: str,
) -> None:
    """14 tables du CDC (migration 0001) + `jeton_session` (migration 0002,
    L2-T1 : sessions de `DatabaseStrategy`, table d'infrastructure hors CDC)
    + `commentaire` (migration 0012, commentaires sur les lignes d'un bon)
    + `grille_import`/`grille_prix` (migration 0013, grilles de prix
    fournisseur -- phase 3)
    + les 5 tables de l'IA (migration 0014 : `appel_ia`,
    `synthese_commentaires`, `synthese_action`, `explication_alerte`,
    `prix_internet`)."""
    url = url_base_migrations(test_database_url)
    preparer_base(url)  # crée la base si besoin, puis upgrade head

    tables = _lister_tables(url)
    assert len(tables) == 23

    command.downgrade(_config(url), "base")
    assert _lister_tables(url) == []

    command.upgrade(_config(url), "head")
    assert len(_lister_tables(url)) == 23


